"""Contratos puros: sin Django, ORM ni scikit-learn."""
from typing import Protocol,ContextManager
from .entities import Patient
class ClinicalRepository(Protocol):
    def atomic(self)->ContextManager:...
    def list_patients(self,patient_id:int|None=None)->list[Patient]:...
    def get_patient(self,patient_id:int)->Patient|None:...
    def create_patient(self,data:dict)->Patient:...
    def update_patient(self,patient_id:int,data:dict)->Patient:...
    def add_entry(self,patient_id:int,author_id:int,kind:str,data:dict)->dict:...
    def entries(self,patient_id:int,kind:str)->list[dict]:...
    def audit(self,actor_id:int,action:str,entity:str,entity_id:int|None=None)->None:...
class RiskModel(Protocol):
    def infer(self,features:dict)->dict:...
    def metrics(self)->dict:...
class PatientAccounts(Protocol):
    def validate(self,username:str,password:str)->None:...
    def create_patient_account(self,username:str,password:str,patient_id:int)->int:...
class LiveRepository(Protocol):
    def atomic(self)->ContextManager:...
    def patient(self,pid:int)->Patient|None:...
    def lock_patient(self,pid:int)->None:...
    def active(self,pid:int,now)->bool:...
    def create(self,pid:int,uid:int,meta:dict,hash:str,expires)->dict:...
    def get(self,sid,lock:bool=False)->dict|None:...
    def calibration(self,id:int)->dict|None:...
    def create_calibration(self,uid:int,device:str,reference:str,data:dict)->dict:...
    def samples(self,sid,after:int,limit:int)->list[dict]:...
    def latest(self,sid)->dict|None:...
    def existing_sample(self,sid,seq:int)->dict|None:...
    def add_sample(self,s:dict,data:dict)->None:...
    def close(self,s:dict,now)->None:...
    def add_reading(self,pid:int,uid:int,data:dict)->int:...
    def audit(self,actor_id:int,action:str,entity:str,entity_id:int|None=None)->None:...
